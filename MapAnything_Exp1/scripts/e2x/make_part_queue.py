"""Make scripts/session_queue_e2x_part.sh from scripts/session_queue_e2x.sh (2026-11-08, shared A100 now free).

Why: one runner process uses ~18% of the A100 (CPU-bound per process); the main queue runs the three models one after
another with at most 3 processes. The part queue runs ONE model's section of the main queue (the same job lines,
copied, so the jobs cannot drift) beside the main queue:
  bash scripts/session_queue_e2x_part.sh px|ov
Differences from the main queue (orchestration only; experiment code, configs and job lines unchanged):
  - its own jobs file ($L/jobs_<part>.txt) and GPU budget file ($L/gpu_budget_<part>_gb, default PART_BUDGET_GB=30);
  - process cap MAX_N (default 4) and 1 process per CPUS_PER CPUs (default 2) instead of 4 and 4;
  - Pi3X waits for $L/ready_pi3x.parallel: ready_pi3x is renamed to that, so the main queue, which waits for
    ready_pi3x after its MapAnything part, never starts the Pi3X or OmniVGGT jobs itself (no two writers on one job);
  - logs "PART <part> start" / "PART_<PART>_DONE" in the shared session.txt.
When MapAnything and both parts are done, SESSION_GPU_DONE is written by hand (or by the part that finishes last,
see the end of the generated script).
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "session_queue_e2x.sh")
DST = os.path.join(HERE, "..", "session_queue_e2x_part.sh")
s = open(SRC, encoding="utf-8").read()
lines = s.split("\n")
i_ma = next(i for i, l in enumerate(lines) if l.startswith("# ---") and "MapAnything" in l)
i_px = next(i for i, l in enumerate(lines) if l.startswith("# ---") and "Pi3X" in l)
i_ov = next(i for i, l in enumerate(lines) if l.startswith("# ---") and "OmniVGGT" in l)
i_end = next(i for i, l in enumerate(lines) if 'log "SESSION_GPU_DONE"' in l)
head = "\n".join(lines[:i_ma])
px = "\n".join(lines[i_px:i_ov])
ov = "\n".join(lines[i_ov:i_end])

head = head.replace('set -euo pipefail', 'set -euo pipefail\nPART=${1:?usage: session_queue_e2x_part.sh px|ov}\n'
                    'case "$PART" in px|ov) ;; *) echo "part must be px or ov" >&2; exit 2 ;; esac', 1)
head = head.replace('g=$(cat "$L/gpu_budget_gb" 2>/dev/null || echo "${GPU_BUDGET_GB:-32}")',
                    'g=$(cat "$L/gpu_budget_${PART}_gb" 2>/dev/null || echo "${PART_BUDGET_GB:-30}")')
head = head.replace('c=$(( $(nproc) / 4 ))', 'c=$(( $(nproc) / ${CPUS_PER:-2} ))')
head = head.replace('[ "$n" -gt 4 ] && n=4', '[ "$n" -gt "${MAX_N:-4}" ] && n=${MAX_N:-4}')
head = head.replace('"$L/jobs.txt"', '"$L/jobs_${PART}.txt"')
head = re.sub(r'log "start e2x session A.*?\n.*?\n', 'log "PART $PART start (beside the main queue), budget $(( $(budget_mb) / 1024 )) GB, '
              'free now $(( $(free_mb) / 1024 )) GB"\n', head, count=1, flags=re.S)
for need in ('jobs_${PART}', 'gpu_budget_${PART}_gb', 'CPUS_PER', 'MAX_N', 'PART $PART start'):
    assert need in head, need
px = px.replace("wait_for ready_pi3x FAILED_pi3x", "wait_for ready_pi3x.parallel FAILED_pi3x")
assert "ready_pi3x.parallel" in px
body = {"px": px, "ov": ov}
out = (head + "\n\n" + 'if [ "$PART" = px ]; then\n' + body["px"] + '\nfi\n'
       + 'if [ "$PART" = ov ]; then\n' + body["ov"] + '\nfi\n'
       + 'log "PART_${PART^^}_DONE"\n')
hdr = ("#!/usr/bin/env bash\n# GENERATED by scripts/e2x/make_part_queue.py from scripts/session_queue_e2x.sh; do not edit."
       "\n# One model's part of the session-A queue, run beside the main queue (see the generator's docstring).\n")
out = hdr + out.split("\n", 1)[1]
open(DST, "w", encoding="utf-8", newline="\n").write(out)
print("wrote", DST)
